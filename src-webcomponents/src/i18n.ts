export const LANGUAGE_NAMES = {
    en: 'English', de: 'Deutsch', ru: 'Русский', pt: 'Português', nl: 'Nederlands',
    fr: 'Français', it: 'Italiano', es: 'Español', pl: 'Polski', uk: 'Українська', 'zh-cn': '简体中文',
} as const;
export type WidgetLanguage = keyof typeof LANGUAGE_NAMES;
const dictionaries: Record<WidgetLanguage, Dictionary> = { en, de, ru, pt, nl, fr, it, es, pl, uk, 'zh-cn': zhCn };

export function widgetText(key: WidgetTextKey, language: WidgetLanguage): string {
    return dictionaries[language][key];
}
export function widgetLabel(key: WidgetTextKey): Record<WidgetLanguage, string> {
    return Object.fromEntries(Object.keys(LANGUAGE_NAMES).map(language =>
        [language, dictionaries[language as WidgetLanguage][key]])) as Record<WidgetLanguage, string>;
}
export function widgetLanguage(value: string | undefined): WidgetLanguage {
    const language = (value || '').toLowerCase().replace('_', '-');
    if (language.startsWith('zh')) return 'zh-cn';
    const short = language.split('-')[0] as WidgetLanguage;
    return short in LANGUAGE_NAMES ? short : 'en';
}
